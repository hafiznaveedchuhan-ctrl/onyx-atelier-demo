import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const dir = join(process.cwd(), 'knowledge');
const files = readdirSync(dir).filter(f => f.endsWith('.md')).sort();
const text = files.map(f => `### FILE: ${f}\n${readFileSync(join(dir, f), 'utf8').trim()}`).join('\n\n');
writeFileSync(join(process.cwd(), 'lib', 'knowledge.generated.ts'),
  `// Generated by scripts/build-knowledge.mjs. Do not edit.\nexport const KNOWLEDGE = ${JSON.stringify(text)};\nexport const KNOWLEDGE_FILES = ${JSON.stringify(files)};\n`);
console.log(`knowledge: ${files.length} files compiled`);
